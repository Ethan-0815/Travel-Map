// 构建条目与别名索引
const ENTRIES = CITIES.map(([name, nameZh, country, countryZh, lat, lng]) => ({
  name,
  nameZh,
  country,
  countryZh,
  lat,
  lng,
}));

const ALIAS = new Map(); // 小写英文/中文 -> entry
for (const e of ENTRIES) {
  ALIAS.set(e.name.toLowerCase(), e);
  ALIAS.set(e.nameZh, e);
}

/** 精确查找（英文名或中文名） */
export function lookupCity(query) {
  if (!query) return null;
  const q = query.trim();
  return ALIAS.get(q.toLowerCase()) || ALIAS.get(q) || null;
}

/** 搜索：前缀优先 + 包含匹配，返回最多 limit 个结果 */
export function searchCities(query, limit = 6) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];
  const starts = [];
  const contains = [];
  for (const e of ENTRIES) {
    if (e.name.toLowerCase().startsWith(q) || e.nameZh.startsWith(q)) {
      starts.push(e);
    } else if (e.name.toLowerCase().includes(q) || e.nameZh.includes(q)) {
      contains.push(e);
    }
  }
  return [...starts, ...contains].slice(0, limit);
}
